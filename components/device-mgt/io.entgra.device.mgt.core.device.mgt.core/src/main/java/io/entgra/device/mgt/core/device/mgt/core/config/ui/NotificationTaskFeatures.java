package io.entgra.device.mgt.core.device.mgt.core.config.ui;

import javax.xml.bind.annotation.XmlElement;
import javax.xml.bind.annotation.XmlRootElement;
import java.util.ArrayList;
import java.util.List;

@XmlRootElement(name = "NotificationTaskFeatures")
public class NotificationTaskFeatures {

    private List<NotificationTaskFeature> features = new ArrayList<>();

    @XmlElement(name = "Feature")
    public List<NotificationTaskFeature> getFeatures() {
        return features;
    }

    public void setFeatures(List<NotificationTaskFeature> features) {
        this.features = features != null ? features : new ArrayList<>();
    }
}
