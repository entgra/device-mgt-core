CREATE TABLE IF NOT EXISTS DM_OIDC_SESSION_STATE (
    ISSUER VARCHAR(255) NOT NULL, CLIENT_ID VARCHAR(255) NOT NULL, SID VARCHAR(255) NOT NULL,
    SUBJECT VARCHAR(255) DEFAULT NULL, APPLICATION_NAME VARCHAR(100) NOT NULL,
    SESSION_STATUS VARCHAR(16) NOT NULL, LOGOUT_JTI VARCHAR(255) DEFAULT NULL,
    CREATED_AT BIGINT NOT NULL, LAST_SEEN_AT BIGINT NOT NULL,
    REVOKED_AT BIGINT DEFAULT NULL, EXPIRES_AT BIGINT NOT NULL,
    PRIMARY KEY (ISSUER, CLIENT_ID, SID),
    INDEX IDX_DM_OIDC_STATE_EXPIRY (EXPIRES_AT)
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS DM_OIDC_SESSION_MAPPING (
    ISSUER VARCHAR(255) NOT NULL, CLIENT_ID VARCHAR(255) NOT NULL, SID VARCHAR(255) NOT NULL,
    APPLICATION_NAME VARCHAR(100) NOT NULL, HTTP_SESSION_ID VARCHAR(128) NOT NULL,
    CREATED_AT BIGINT NOT NULL, LAST_SEEN_AT BIGINT NOT NULL, SESSION_TIMEOUT_MS BIGINT NOT NULL,
    EXPIRES_AT BIGINT NOT NULL,
    PRIMARY KEY (APPLICATION_NAME, HTTP_SESSION_ID),
    INDEX IDX_DM_OIDC_MAPPING_SID (ISSUER, CLIENT_ID, SID),
    CONSTRAINT FK_DM_OIDC_MAPPING_STATE FOREIGN KEY (ISSUER, CLIENT_ID, SID)
        REFERENCES DM_OIDC_SESSION_STATE (ISSUER, CLIENT_ID, SID) ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS DM_OIDC_SESSION_CLEANUP (
    TASK_NAME VARCHAR(64) NOT NULL PRIMARY KEY, LAST_RUN_AT BIGINT NOT NULL
) ENGINE = InnoDB;
INSERT IGNORE INTO DM_OIDC_SESSION_CLEANUP (TASK_NAME, LAST_RUN_AT)
    VALUES ('OIDC_SESSION_CLEANUP', 0);
