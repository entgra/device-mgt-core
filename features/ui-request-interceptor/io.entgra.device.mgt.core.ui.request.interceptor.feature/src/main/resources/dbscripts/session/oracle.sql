CREATE TABLE DM_OIDC_SESSION_STATE (
    ISSUER VARCHAR2(255) NOT NULL, CLIENT_ID VARCHAR2(255) NOT NULL, SID VARCHAR2(255) NOT NULL,
    SUBJECT VARCHAR2(255), APPLICATION_NAME VARCHAR2(100) NOT NULL, SESSION_STATUS VARCHAR2(16) NOT NULL,
    LOGOUT_JTI VARCHAR2(255), CREATED_AT NUMBER(19) NOT NULL,
    LAST_SEEN_AT NUMBER(19) NOT NULL, REVOKED_AT NUMBER(19), EXPIRES_AT NUMBER(19) NOT NULL,
    CONSTRAINT PK_DM_OIDC_SESSION_STATE PRIMARY KEY (ISSUER, CLIENT_ID, SID)
);
CREATE INDEX IDX_DM_OIDC_STATE_EXPIRY ON DM_OIDC_SESSION_STATE (EXPIRES_AT);

CREATE TABLE DM_OIDC_SESSION_MAPPING (
    ISSUER VARCHAR2(255) NOT NULL, CLIENT_ID VARCHAR2(255) NOT NULL, SID VARCHAR2(255) NOT NULL,
    APPLICATION_NAME VARCHAR2(100) NOT NULL, HTTP_SESSION_ID VARCHAR2(128) NOT NULL,
    CREATED_AT NUMBER(19) NOT NULL, LAST_SEEN_AT NUMBER(19) NOT NULL,
    SESSION_TIMEOUT_MS NUMBER(19) NOT NULL, EXPIRES_AT NUMBER(19) NOT NULL,
    CONSTRAINT PK_DM_OIDC_SESSION_MAPPING PRIMARY KEY (APPLICATION_NAME, HTTP_SESSION_ID),
    CONSTRAINT FK_DM_OIDC_MAPPING_STATE FOREIGN KEY (ISSUER, CLIENT_ID, SID)
        REFERENCES DM_OIDC_SESSION_STATE (ISSUER, CLIENT_ID, SID) ON DELETE CASCADE
);
CREATE INDEX IDX_DM_OIDC_MAPPING_SID ON DM_OIDC_SESSION_MAPPING (ISSUER, CLIENT_ID, SID);

CREATE TABLE DM_OIDC_SESSION_CLEANUP (
    TASK_NAME VARCHAR2(64) NOT NULL PRIMARY KEY, LAST_RUN_AT NUMBER(19) NOT NULL
);
