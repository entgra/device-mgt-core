IF NOT EXISTS (SELECT * FROM SYS.OBJECTS WHERE OBJECT_ID = OBJECT_ID(N'[DBO].[DM_OIDC_SESSION_STATE]') AND TYPE IN (N'U'))
CREATE TABLE DM_OIDC_SESSION_STATE (
    ISSUER VARCHAR(255) NOT NULL, CLIENT_ID VARCHAR(255) NOT NULL, SID VARCHAR(255) NOT NULL,
    SUBJECT VARCHAR(255) NULL, APPLICATION_NAME VARCHAR(100) NOT NULL, SESSION_STATUS VARCHAR(16) NOT NULL,
    LOGOUT_JTI VARCHAR(255) NULL, CREATED_AT BIGINT NOT NULL,
    LAST_SEEN_AT BIGINT NOT NULL, REVOKED_AT BIGINT NULL, EXPIRES_AT BIGINT NOT NULL,
    CONSTRAINT PK_DM_OIDC_SESSION_STATE PRIMARY KEY (ISSUER, CLIENT_ID, SID)
);
IF NOT EXISTS (SELECT * FROM SYS.INDEXES WHERE NAME = 'IDX_DM_OIDC_STATE_EXPIRY' AND OBJECT_ID = OBJECT_ID('DM_OIDC_SESSION_STATE'))
CREATE INDEX IDX_DM_OIDC_STATE_EXPIRY ON DM_OIDC_SESSION_STATE (EXPIRES_AT);

IF NOT EXISTS (SELECT * FROM SYS.OBJECTS WHERE OBJECT_ID = OBJECT_ID(N'[DBO].[DM_OIDC_SESSION_MAPPING]') AND TYPE IN (N'U'))
CREATE TABLE DM_OIDC_SESSION_MAPPING (
    ISSUER VARCHAR(255) NOT NULL, CLIENT_ID VARCHAR(255) NOT NULL, SID VARCHAR(255) NOT NULL,
    APPLICATION_NAME VARCHAR(100) NOT NULL, HTTP_SESSION_ID VARCHAR(128) NOT NULL,
    CREATED_AT BIGINT NOT NULL, LAST_SEEN_AT BIGINT NOT NULL, SESSION_TIMEOUT_MS BIGINT NOT NULL,
    EXPIRES_AT BIGINT NOT NULL,
    CONSTRAINT PK_DM_OIDC_SESSION_MAPPING PRIMARY KEY (APPLICATION_NAME, HTTP_SESSION_ID),
    CONSTRAINT FK_DM_OIDC_MAPPING_STATE FOREIGN KEY (ISSUER, CLIENT_ID, SID)
        REFERENCES DM_OIDC_SESSION_STATE (ISSUER, CLIENT_ID, SID) ON DELETE CASCADE
);
IF NOT EXISTS (SELECT * FROM SYS.INDEXES WHERE NAME = 'IDX_DM_OIDC_MAPPING_SID' AND OBJECT_ID = OBJECT_ID('DM_OIDC_SESSION_MAPPING'))
CREATE INDEX IDX_DM_OIDC_MAPPING_SID ON DM_OIDC_SESSION_MAPPING (ISSUER, CLIENT_ID, SID);

IF NOT EXISTS (SELECT * FROM SYS.OBJECTS WHERE OBJECT_ID = OBJECT_ID(N'[DBO].[DM_OIDC_SESSION_CLEANUP]') AND TYPE IN (N'U'))
CREATE TABLE DM_OIDC_SESSION_CLEANUP (
    TASK_NAME VARCHAR(64) NOT NULL PRIMARY KEY, LAST_RUN_AT BIGINT NOT NULL
);
IF NOT EXISTS (SELECT 1 FROM DM_OIDC_SESSION_CLEANUP WHERE TASK_NAME = 'OIDC_SESSION_CLEANUP')
INSERT INTO DM_OIDC_SESSION_CLEANUP (TASK_NAME, LAST_RUN_AT) VALUES ('OIDC_SESSION_CLEANUP', 0);
