-- LEGACY DM_NOTIFICATION_ARCH TABLE --
CREATE TABLE IF NOT EXISTS DM_NOTIFICATION_ARCH (
    NOTIFICATION_ID INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    OPERATION_ID INTEGER NOT NULL,
    TENANT_ID INTEGER NOT NULL,
    STATUS VARCHAR(10) NULL,
    DESCRIPTION VARCHAR(1000) NULL,
    ARCHIVED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_NOT_ARCH ON DM_NOTIFICATION_ARCH(ARCHIVED_AT);
-- END LEGACY DM_NOTIFICATION_ARCH TABLE --

CREATE TABLE DM_REALTIME_NOTIFICATION_ARCH (
    NOTIFICATION_ID NUMBER(10) NOT NULL,
    NOTIFICATION_CONFIG_ID NUMBER(10) NOT NULL,
    TENANT_ID NUMBER(10) NOT NULL,
    NOTIFICATION_CONTEXT VARCHAR2(1000) NULL,
    TYPE VARCHAR2(20) NOT NULL,
    CREATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_DM_REALTIME_NOTIFICATION_ARCH PRIMARY KEY (NOTIFICATION_ID)
);

CREATE SEQUENCE DM_REALTIME_NOTIFICATION_ARCH_seq START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER DM_REALTIME_NOTIFICATION_ARCH_bir
    BEFORE INSERT ON DM_REALTIME_NOTIFICATION_ARCH
    FOR EACH ROW
BEGIN
    IF :NEW.NOTIFICATION_ID IS NULL THEN
SELECT DM_REALTIME_NOTIFICATION_ARCH_seq.NEXTVAL INTO :NEW.NOTIFICATION_ID FROM DUAL;
END IF;
END;
/

CREATE INDEX IDX_REALTIME_NOTF_CONFIG_ID ON DM_REALTIME_NOTIFICATION_ARCH(NOTIFICATION_CONFIG_ID);
CREATE INDEX IDX_REALTIME_NOTF_TENANT_ID ON DM_REALTIME_NOTIFICATION_ARCH(TENANT_ID);
CREATE INDEX IDX_REALTIME_NOTF_CREATED_TIMESTAMP ON DM_REALTIME_NOTIFICATION_ARCH(CREATED_TIMESTAMP);
/
